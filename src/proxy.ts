import { NextResponse, type NextRequest } from "next/server";

/**
 * Setzt die Content-Security-Policy mit frischem Nonce pro Anfrage.
 * Next.js versieht seine eigenen Inline-Skripte automatisch mit dem Nonce,
 * sobald der CSP-Header auf der Anfrage liegt.
 *
 * `style-src` braucht 'unsafe-inline': React rendert Event-Farben als
 * style-Attribute, und Veranstalter können eigenes CSS hinterlegen — beides
 * lässt sich nicht per Nonce abdecken. Das Risiko bleibt auf CSS beschränkt.
 */
export function proxy(request: NextRequest) {
  const nonce = Buffer.from(crypto.randomUUID()).toString("base64");
  const isDev = process.env.NODE_ENV === "development";

  const csp = [
    "default-src 'self'",
    `script-src 'self' 'nonce-${nonce}' 'strict-dynamic'${isDev ? " 'unsafe-eval'" : ""}`,
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' blob: data:",
    "font-src 'self'",
    "connect-src 'self'",
    "media-src 'none'",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
    "upgrade-insecure-requests",
  ].join("; ");

  const requestHeaders = new Headers(request.headers);
  requestHeaders.set("x-nonce", nonce);
  requestHeaders.set("Content-Security-Policy", csp);

  const response = NextResponse.next({ request: { headers: requestHeaders } });
  response.headers.set("Content-Security-Policy", csp);
  return response;
}

export const config = {
  matcher: [
    {
      source: "/((?!_next/static|_next/image|favicon.ico).*)",
      missing: [
        { type: "header", key: "next-router-prefetch" },
        { type: "header", key: "purpose", value: "prefetch" },
      ],
    },
  ],
};
